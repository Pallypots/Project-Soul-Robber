#!/usr/bin/env python3
"""List original source-file names left in the XBE (debug/assert strings) and
which functions reference each one. These are the developers' own file names,
used to organise recovered code into the same translation units.
Usage: py -3 tools/source_names.py > docs/source_files.md"""
import csv, os, re, struct, sys
sys.path.insert(0, os.path.dirname(__file__))
from xbe_inventory import Xbe

ROOT = os.path.join(os.path.dirname(__file__), "..")
x = Xbe(os.environ.get("OOGIE_XBE", "C:/ProjectOogie/game/default.xbe"))

names = {}
for s in x.sections:
    if s["name"] not in (".rdata", ".data"):
        continue
    b = x.data[s["raw"]:s["raw"] + s["rsize"]]
    for m in re.finditer(rb"[\x20-\x7e]{3,200}\.(?:c|cpp|h)\x00", b):
        t = m.group()[:-1].decode()
        k = t.find("\\Project")
        off = m.start()
        if k > 0 and not t.startswith("#"):
            off += k          # string really starts at the backslash
            t = t[k:]
        if "\\" in t or "/" in t or t.endswith((".c", ".cpp")):
            names[s["va"] + off] = t

# functions whose code contains the address of a name as an immediate (push imm32)
funcs = [r for r in csv.DictReader(open(os.path.join(ROOT, "config", "inventory", "functions.csv")))
         if r["owner"] == "game"]
refs = {a: [] for a in names}
for r in funcs:
    va, n = int(r["va"], 16), int(r["size"])
    try:
        code = x.read_va(va, n)
    except Exception:
        continue
    for i in range(len(code) - 4):
        v = struct.unpack_from("<I", code, i)[0]
        if v in refs:
            refs[v].append(va)

print("# Original source file names in the XBE\n")
print("Generated by `tools/source_names.py`. Strings are the developers' own paths (assert/allocator")
print("arguments); functions listed contain the string's address, so they were compiled from that file.\n")
print("| String VA | File | Referencing game functions |\n|---|---|---|")
for a in sorted(names):
    fs = sorted(set(refs[a]))
    shown = ", ".join(f"{f:#010x}" for f in fs[:12]) + (f" (+{len(fs) - 12})" if len(fs) > 12 else "")
    print(f"| {a:#010x} | `{names[a]}` | {shown} |")
